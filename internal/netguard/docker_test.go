func TestDockerScopeOnlyForeignDisjointObservedBridges(t *testing.T) {
	i, v, _ := dockerTopology(t)
	for _, mutate := range []func(*Inputs, *Inventory){
		func(i *Inputs, v *Inventory) { i.Role = "ru"; i.HostPublicIPv4 = i.RUIPv4 },
		func(i *Inputs, v *Inventory) { i.Transit = netip.MustParsePrefix("172.29.172.0/30") },
		func(i *Inputs, v *Inventory) {
			v.Addresses[len(v.Addresses)-1].Prefix = netip.MustParsePrefix("172.29.172.1/8")
		},
		func(i *Inputs, v *Inventory) {
			v.Addresses[len(v.Addresses)-1].Prefix = netip.MustParsePrefix("46.9.10.1/24")
		},
		func(i *Inputs, v *Inventory) { v.Addresses = append(v.Addresses, v.Addresses[len(v.Addresses)-1]) },
		func(i *Inputs, v *Inventory) {
			v.Addresses[len(v.Addresses)-1].Prefix = netip.MustParsePrefix("172.17.0.1/24")
		},
	} {
		copyV := v
		copyV.Addresses = append([]Address(nil), v.Addresses...)
		copyI := i
		mutate(&copyI, &copyV)
		if _, err := ForeignDockerScope(copyI, copyV); !errors.Is(err, ErrDockerScope) {
			t.Fatal("unsupported or overlapping scope accepted")
		}
	}
	if RequireScopedIPTables([]byte(dockerSave), "ip", DockerScope{}) == nil {
		t.Fatal("zero scope permits rewrite")
	}
}

func TestDockerLegacyClosedNATRecipesAndForwardingFence(t *testing.T) {
	_, _, scope := dockerTopology(t)
	if RequireScopedIPTables([]byte(dockerSave), "ip", scope) != nil || RequireScopedIPTables([]byte(emptyIPv6Save), "ip6", scope) != nil {
		t.Fatal("supported synthetic Docker listing rejected")
	}
	needed, err := LegacyForwardingNeedsGuard([]byte(dockerSave), scope)
	if err != nil || !needed || VerifyLegacyForwardingGuard([]byte(dockerSave), scope) == nil {
		t.Fatal("Docker default DROP falsely accepted as passing")
	}
	own := "-A FORWARD -i fvpn-host -j ACCEPT\n-A FORWARD -o fvpn-host -j ACCEPT\n"
	installed := strings.Replace(dockerSave, "-A FORWARD -j DOCKER-USER", own+"-A FORWARD -j DOCKER-USER", 1)
	if VerifyLegacyForwardingGuard([]byte(installed), scope) != nil {
		t.Fatal("exact owned head rejected")
	}
	before, e1 := LegacyPolicySHA256([]byte(dockerSave), "ip", scope, false)
	after, e2 := LegacyPolicySHA256([]byte(installed), "ip", scope, true)
	if e1 != nil || e2 != nil || before != after {
		t.Fatal("supplements changed original semantic baseline")
	}
	countersChanged := strings.ReplaceAll(installed, "[0:0]", "[9223372036854775808:18446744073709551615]")
	after, err = LegacyPolicySHA256([]byte(countersChanged), "ip", scope, true)
	if err != nil || after != before {
		t.Fatal("unsigned counter changes affect baseline")
	}
	modified := strings.Replace(installed, ":FORWARD DROP", ":FORWARD ACCEPT", 1)
	after, err = LegacyPolicySHA256([]byte(modified), "ip", scope, true)
	if err != nil || after == before {
		t.Fatal("Docker policy mutation hidden by own supplements")
	}
	for _, bad := range []string{
		strings.Replace(installed, "-i fvpn-host -j ACCEPT", "-i fvpn-host -m conntrack --ctstate NEW -j ACCEPT", 1),
		strings.Replace(installed, "-i fvpn-host -j ACCEPT", "-i fvpn-host -m conntrack -j ACCEPT", 1),
		strings.Replace(installed, "-i fvpn-host -j ACCEPT", "-i fvpn-host -m state -j ACCEPT", 1),
		strings.Replace(installed, "-i fvpn-host -j ACCEPT", "-i fvpn-host -m addrtype -j ACCEPT", 1),
		strings.Replace(installed, "-i fvpn-host -j ACCEPT", "-i fvpn-host -j DROP", 1),
		strings.Replace(installed, "-i fvpn-host -j ACCEPT", "-o fvpn-host -j ACCEPT", 1),
		strings.Replace(installed, "-A DOCKER-USER -j RETURN", "-A FORWARD -i fvpn-host -j ACCEPT\n-A DOCKER-USER -j RETURN", 1),
		strings.Replace(installed, own, "", 1),
	} {
		if VerifyLegacyForwardingGuard([]byte(bad), scope) == nil {
			t.Fatal("partial/reordered/duplicate/constrained owned acceptance accepted")
		}
	}
	if _, err := LegacyPolicySHA256([]byte(installed), "ip", scope, false); err == nil {
		t.Fatal("baseline accepts preexisting owned interface rules")
	}
}

func TestDockerLegacyRejectsRewriteOutsideProvenDisjointScope(t *testing.T) {
	_, _, scope := dockerTopology(t)
	for _, mutation := range [][2]string{
		{"--dst-type LOCAL", "--src-type LOCAL"},
		{"-A PREROUTING -m addrtype --dst-type LOCAL -j DOCKER", "-A PREROUTING -j DOCKER"},
		{"-s 172.29.172.0/24", "-s 0.0.0.0/0"},
		{"-s 172.29.172.0/24", "! -s 172.29.172.0/24"},
		{"-s 172.29.172.0/24", "-s 10.231.240.0/30"},
		{"! -o amn0 -j MASQUERADE", "! -o docker0 -j MASQUERADE"},
		{"--dport 30759 -j DNAT", "--dport 443 -j DNAT"},
		{"--dport 30759 -j DNAT", "--dport 30760 -j DNAT"},
		{"! -i amn0 -p udp", "-i amn0 -p udp"},
		{"172.29.172.2:30759", "10.231.240.2:30759"},
		{"172.29.172.2:30759", "172.29.172.1:30759"},
		{"172.29.172.2:30759", "172.29.172.2:443"},
		{"-j MASQUERADE", "-j MARK --set-mark 1"},
		{"-j MASQUERADE", "-j NFQUEUE"},
		{"-m udp --dport 30759 -j DNAT", "-m udp --dport 30759 -m unknown -j DNAT"},
		{"-j DNAT --to-destination", "-j REDIRECT --to-ports"},
		{"-p udp -m udp --dport 30759 -j DNAT", "-p tcp -m tcp --dport 30759 -j DNAT"},
		{"-A DOCKER ! -i amn0", "-A POSTROUTING ! -i amn0"},
	} {
		bad := strings.Replace(dockerSave, mutation[0], mutation[1], 1)
		if bad == dockerSave {
			t.Fatal("test mutation did not match")
		}
		if RequireScopedIPTables([]byte(bad), "ip", scope) == nil {
			t.Fatal("unsupported Docker rule accepted", mutation[0])
		}
	}
	for _, injection := range []string{
		"-A FORWARD -j CT\n", "-A FORWARD -j MARK\n", "-A FORWARD -j QUEUE\n", "-A FORWARD -j TPROXY\n", "-A FORWARD -j TRACE\n",
	} {
		bad := strings.Replace(dockerSave, "-A FORWARD -j DOCKER-USER", injection+"-A FORWARD -j DOCKER-USER", 1)
		if RequireScopedIPTables([]byte(bad), "ip", scope) == nil {
			t.Fatal("unknown/assignment legacy target accepted")
		}
	}
	// Renaming a user chain to a reserved extension cannot hide target effects.
	bad := strings.ReplaceAll(dockerSave, "DOCKER-USER", "MARK")
	if RequireScopedIPTables([]byte(bad), "ip", scope) == nil {
		t.Fatal("reserved extension shadow chain accepted")
	}
	if RequireScopedIPTables([]byte(dockerSave), "ip6", scope) == nil {
		t.Fatal("IPv6 NAT accepted through IPv4 bridge subset")
	}
}

