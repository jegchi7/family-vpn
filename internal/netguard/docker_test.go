func dockerNft(t *testing.T, own bool) []byte {
	t.Helper()
	objects := []any{
		map[string]any{"metainfo": map[string]any{"version": "0.9.3", "release_name": "fixture", "json_schema_version": 1}},
		map[string]any{"table": map[string]any{"family": "ip", "name": "filter", "handle": 1}},
		map[string]any{"chain": map[string]any{"family": "ip", "table": "filter", "name": "FORWARD", "type": "filter", "hook": "forward", "prio": 0, "policy": "drop", "handle": 2}},
	}
	if own {
		for _, key := range []string{"iifname", "oifname"} {
			objects = append(objects, map[string]any{"rule": map[string]any{"family": "ip", "table": "filter", "chain": "FORWARD", "expr": ownedForwardNFT(key)}})
		}
	}
	objects = append(objects,
		map[string]any{"rule": map[string]any{"family": "ip", "table": "filter", "chain": "FORWARD", "expr": []any{map[string]any{"counter": map[string]any{"packets": 10, "bytes": 400}}, map[string]any{"drop": nil}}}},
		map[string]any{"table": map[string]any{"family": "ip", "name": "nat"}},
	)
	for _, q := range []struct {
		name, hook string
		priority   int
	}{{"PREROUTING", "prerouting", -100}, {"INPUT", "input", 100}, {"OUTPUT", "output", -100}, {"POSTROUTING", "postrouting", 100}} {
		objects = append(objects, map[string]any{"chain": map[string]any{"family": "ip", "table": "nat", "name": q.name, "type": "nat", "hook": q.hook, "prio": q.priority, "policy": "accept"}})
	}
	objects = append(objects, map[string]any{"chain": map[string]any{"family": "ip", "table": "nat", "name": "DOCKER"}})
	match := func(left any, op string, right any) any {
		return map[string]any{"match": map[string]any{"op": op, "left": left, "right": right}}
	}
	payload := func(protocol, field string) any {
		return map[string]any{"payload": map[string]any{"protocol": protocol, "field": field}}
	}
	meta := func(key string) any { return map[string]any{"meta": map[string]any{"key": key}} }
	rule := func(chain string, expr ...any) {
		objects = append(objects, map[string]any{"rule": map[string]any{"family": "ip", "table": "nat", "chain": chain, "expr": expr}})
	}
	for _, chain := range []string{"PREROUTING", "OUTPUT"} {
		rule(chain, match(map[string]any{"fib": map[string]any{"result": "type", "flags": []any{"daddr"}}}, "==", "local"), map[string]any{"counter": map[string]any{"packets": 0, "bytes": 0}}, map[string]any{"jump": map[string]any{"target": "DOCKER"}})
	}
	rule("POSTROUTING", match(payload("ip", "saddr"), "==", map[string]any{"prefix": map[string]any{"addr": "172.29.172.0", "len": 24}}), match(meta("oifname"), "!=", "amn0"), map[string]any{"masquerade": nil})
	rule("DOCKER", match(meta("iifname"), "==", "amn0"), map[string]any{"return": nil})
	rule("DOCKER", match(meta("iifname"), "!=", "amn0"), match(meta("l4proto"), "==", "udp"), match(payload("udp", "dport"), "==", 30759), map[string]any{"dnat": map[string]any{"addr": "172.29.172.2", "port": 30759}})
	b, err := json.Marshal(map[string]any{"nftables": objects})
	if err != nil {
		t.Fatal(err)
	}
	return b
}

func TestDockerNftClosedSubsetKeepsStrictGateAndBaseline(t *testing.T) {
	_, _, scope := dockerTopology(t)
	before, installed := dockerNft(t, false), dockerNft(t, true)
	if RequireNoUnownedPacketRewrite(before) == nil || RequireScopedHostRewrite(before, scope) != nil {
		t.Fatal("scoped exception weakened original strict gate or rejected supported recipe")
	}
	needed, err := NFTForwardingNeedsGuard(before, scope)
	if err != nil || !needed || VerifyNFTForwardingGuard(before, scope) == nil || VerifyNFTForwardingGuard(installed, scope) != nil {
		t.Fatal("shared DROP policy reachability was not separately fenced")
	}
	if _, err := NFTPolicySHA256(installed, scope, false); err == nil {
		t.Fatal("nft baseline accepts preexisting owned interface rules")
	}
	a, e1 := NFTPolicySHA256(before, scope, false)
	b, e2 := NFTPolicySHA256(installed, scope, true)
	if e1 != nil || e2 != nil || a != b {
		t.Fatal("owned supplements changed nft baseline", e1, e2)
	}
	changed := strings.Replace(string(installed), `"packets":10`, `"packets":22`, 1)
	b, err = NFTPolicySHA256([]byte(changed), scope, true)
	if err != nil || a != b {
		t.Fatal("counter change affected semantic baseline")
	}
	changed = strings.Replace(string(installed), `"policy":"drop"`, `"policy":"accept"`, 1)
	b, err = NFTPolicySHA256([]byte(changed), scope, true)
	if err != nil || a == b {
		t.Fatal("unrelated policy mutation hidden")
	}
	for _, mutation := range [][2]string{
		{`"flags":["daddr"]`, `"flags":["saddr"]`},
		{`"right":30759`, `"right":443`},
		{`"addr":"172.29.172.2"`, `"addr":"10.231.240.2"`},
		{`"addr":"172.29.172.0","len":24`, `"addr":"0.0.0.0","len":0`},
		{`"masquerade":null`, `"mangle":{"key":{"meta":{"key":"mark"}},"value":1}`},
		{`"masquerade":null`, `"queue":{"num":0}`},
		{`"masquerade":null`, `"flow":{"op":"add","flowtable":"f"}`},
		{`"masquerade":null`, `"xt":{"name":"MASQUERADE","rev":0,"type":"target"}`},
		{`"prio":-100`, `"prio":-200`},
	} {
		bad := strings.Replace(string(before), mutation[0], mutation[1], 1)
		if bad == string(before) || RequireScopedHostRewrite([]byte(bad), scope) == nil {
			t.Fatal("unsupported nft rewrite/priority accepted", mutation[0])
		}
	}
	for _, bad := range [][]byte{nil, []byte(`{"nftables":[],"nftables":[]}`), append(before, []byte(`{}`)...)} {
		if RequireScopedHostRewrite(bad, scope) == nil {
			t.Fatal("malformed nft listing accepted")
		}
	}
}

func TestDockerForwardInsertionScopesPreserveUnownedTraffic(t *testing.T) {
	for _, backend := range []string{"legacy", "nft"} {
		steps, err := DockerForwardInsertions(backend)
		if err != nil || len(steps) != 2 {
			t.Fatal("closed supplement missing")
		}
		for _, step := range steps {
			if step.Scope != "host" || !strings.Contains(strings.Join(step.Args, " "), HostVeth) || len(step.Stdin) != 0 {
				t.Fatal("shared filter mutation exceeds owned interface scope")
			}
			if backend == "legacy" && (!strings.Contains(strings.Join(step.Args, " "), "-M "+LegacyDisableModuleAutoload) || !strings.Contains(strings.Join(step.Args, " "), "-w 2")) {
				t.Fatal("legacy fixed module deny and bounded lock missing")
			}
			for _, token := range step.Args {
				if token == "flush" || token == "-F" || token == "-P" || token == "policy" || token == "DROP" || token == "ESTABLISHED" {
					t.Fatal("broad Docker mutation or blanket established acceptance")
				}
			}
		}
	}
	if _, err := DockerForwardInsertions("auto"); err == nil {
		t.Fatal("backend autopick accepted")
	}
}

